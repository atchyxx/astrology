  function moonSignsOfDay(input) {
    const start = Date.UTC(input.year, input.month - 1, input.day) - input.tzOffset * 3600000;
    const a = Calc.toSign(Calc.longitudeAt('Moon', start)).sign.name;
    const b = Calc.toSign(Calc.longitudeAt('Moon', start + 86400000 - 60000)).sign.name;
    return a === b ? null : [a, b];
  }

  /**
   * @param {object} data   HoroscopeCalc.calculate の結果
   * @param {object} input  計算に使った入力（時刻不明かどうかなど）
   */
  function reading(data, input) {
    const p = key => data.points.find(x => x.key === key);
    const sections = [];
    const add = (key, title, point, text, note) => sections.push({
      key, title, symbol: point.symbol, sign: signName(point), signSymbol: point.position.sign.symbol, text, note,
      pointName: key === 'mc' ? 'MC' : point.name,
    });

    add('sun', '人柄・あなたらしさ', p('Sun'), SUN[p('Sun').position.index]);

    let moonNote = null;
    if (!input.timeKnown) {
      const both = moonSignsOfDay(input);
      if (both) moonNote = `生まれた時刻によって、月は${both[0]}か${both[1]}になります。時刻がわかると正確になります。`;
    }
    add('moon', '心・ほっとできること', p('Moon'), MOON[p('Moon').position.index], moonNote);

    if (data.houses) add('asc', '第一印象・雰囲気', p('ASC'), ASC[p('ASC').position.index]);
    add('mercury', '考え方・話し方', p('Mercury'), MERCURY[p('Mercury').position.index]);
    add('venus', '愛情・人づきあい', p('Venus'), VENUS[p('Venus').position.index]);
    add('mars', 'がんばり方', p('Mars'), MARS[p('Mars').position.index]);

    const jupiter = p('Jupiter');
    let luck = JUPITER[jupiter.position.index];
    if (data.houses) luck += `特に「${JUPITER_HOUSE[jupiter.house - 1]}」で幸運が広がりやすい星の配置です。`;
    add('jupiter', '幸運を呼ぶ力', jupiter, luck);

    if (data.houses) add('mc', '向いている仕事', p('MC'), MC[p('MC').position.index]);

    // エレメント・クオリティでいちばん多いものを強みにする
    const top = groups => {
      const max = Math.max(...Object.values(groups).map(list => list.length));
      return Object.keys(groups).filter(k => groups[k].length === max);
    };
    const elements = top(data.elements);
    const modes = top(data.modes);
    const elementPart = elements.length >= 3
      ? `${elements.join('・')}のエレメントがバランスよくそろい、いろいろな場面で力を発揮できます。`
      : `${elements.join('と')}のエレメントが多く、${elements.map(e => ELEMENT_TEXT[e]).join('と、')}があります。`;
    const modePart = modes.length >= 3
      ? '始める力・続ける力・変化に合わせる力のバランスがとれています。'
      : `また${modes.map(m => `${m}宮`).join('と')}が多く、${modes.map(m => MODE_TEXT[m]).join('と、')}にすぐれています。`;
    const strength = elementPart + modePart;

    // 調和のアスペクト（120°・60°）を才能の組み合わせとして読む。世代的な遅い天体どうしは除く
    const planets = new Set(Calc.PLANETS.map(pl => pl.key));
    const nameOf = key => Calc.PLANETS.find(pl => pl.key === key).name;
    const talents = data.aspects
      .filter(a => planets.has(a.a) && planets.has(a.b) && (a.aspect.angle === 60 || a.aspect.angle === 120))
      .filter(a => !(SLOW.has(a.a) && SLOW.has(a.b)))
      .sort((x, y) => x.orb - y.orb)
      .slice(0, 4)
      .map(a => ({
        a: a.a, b: a.b, aspect: a.aspect,
        text: `${nameOf(a.a)}の「${GIFT[a.a]}」と${nameOf(a.b)}の「${GIFT[a.b]}」が調和しています（${a.aspect.name}）。${GIFT[a.a]}と${GIFT[a.b]}を組み合わせると、無理なく力を発揮できます。`,
      }));

    return { sections, strength, talents };
  }

  // 人に伝えるための文章
  function toMessage(r, name) {
    const lines = [`【${name ? name + 'さんの' : ''}星が教えてくれるよいところ】`, ''];
    r.sections.forEach(s => {
      lines.push(`◆ ${s.title}（${s.pointName}・${s.sign}）`);
      lines.push(`　${s.text}`);
    });
    lines.push('', '◆ 星のバランスから見た強み', `　${r.strength}`);
    if (r.talents.length) {
      lines.push('', '◆ 才能の組み合わせ');
      r.talents.forEach(t => lines.push(`　${t.text}`));
    }
    return lines.join('\n');
  }

